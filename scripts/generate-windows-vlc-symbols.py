#!/usr/bin/env python3
"""Generate the VLC 3 DLL resolver from the shared core's public API calls."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / 'packages/tangerine_vlc/native'
symbols = sorted(set(re.findall(r'\b(libvlc_[a-z0-9_]+)\s*\(', (root / 'vlc_session.h').read_text())))
header = '''// Generated by scripts/generate-windows-vlc-symbols.py.
#ifndef TANGERINE_VLC_WINDOWS_SYMBOLS_H
#define TANGERINE_VLC_WINDOWS_SYMBOLS_H
#ifdef _WIN32
#include <windows.h>
#include <vlc/vlc.h>
#include <stdexcept>
#include <string>
// Each process retains one module. Sessions own independent libVLC instances.
struct TangerineVlcSymbols {
  HMODULE module = nullptr;
'''
for name in symbols:
    header += f'  decltype(&{name}) {name}_ptr = nullptr;\n'
header += '''  TangerineVlcSymbols() {
    wchar_t executable[32768];
    DWORD length = GetModuleFileNameW(nullptr, executable, 32768);
    if (!length || length >= 32768) throw std::runtime_error("Application path unavailable");
    std::wstring path(executable, length);
    path = path.substr(0, path.find_last_of(L"/\\\\") + 1) + L"libvlc.dll";
    module = LoadLibraryExW(path.c_str(), nullptr, LOAD_LIBRARY_SEARCH_DLL_LOAD_DIR | LOAD_LIBRARY_SEARCH_DEFAULT_DIRS);
    if (!module) throw std::runtime_error("Bundled VideoLAN libvlc.dll/libvlccore.dll could not load");
    try {
'''
for name in symbols:
    header += f'      {name}_ptr = reinterpret_cast<decltype({name}_ptr)>(GetProcAddress(module, "{name}"));\n'
    header += f'      if (!{name}_ptr) throw std::runtime_error("Missing VLC 3 API: {name}");\n'
header += '''      if (std::string(libvlc_get_version_ptr()).rfind("3.", 0) != 0)
        throw std::runtime_error("Tangerine requires the VLC 3 API");
    } catch (...) { FreeLibrary(module); module = nullptr; throw; }
  }
};
inline TangerineVlcSymbols& TangerineVlcApi() {
  static auto* api = new TangerineVlcSymbols();
  return *api;
}
'''
for name in symbols:
    header += f'#define {name} (TangerineVlcApi().{name}_ptr)\n'
header += '#endif\n#endif\n'
(root / 'vlc_windows_symbols.h').write_text(header)
